import { cpSync, mkdirSync, readFileSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { applyStaged, rollback, stagePlugin } from '../lib/repair.js'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const work = join(root, '.selftest-apply')
rmSync(work, { recursive: true, force: true })
mkdirSync(join(work, 'live'), { recursive: true })
cpSync(join(root, 'fixtures', 'toy'), join(work, 'live'), { recursive: true })
const manifest = JSON.parse(readFileSync(join(work, 'live', 'package.json'), 'utf8'))
const plugin = {
  id: '@local/update-guard-toy',
  name: '@local/update-guard-toy',
  title: 'Toy',
  version: '1.0.0',
  kind: 'host',
  enabled: true,
  directory: join(work, 'live'),
  manifest,
  clientInject: [],
  source: [{ path: join(work, 'live', 'index.js'), relative: 'index.js', size: 100 }],
}
const meta = await stagePlugin(plugin, { status: 'ok' }, {
  targetVersion: '0.2.2-rc.1',
  stagingDir: join(work, 'staging'),
  renames: { slots: { 'old.slot': 'new.slot' } },
  cacheDir: join(process.env.DSH_HOME ?? '', 'update-guard', 'cache'),
})
const record = applyStaged(meta, join(work, 'backups'))
const applied = readFileSync(join(work, 'live', 'index.js'), 'utf8')
console.log({ facade: meta.facade, appliedHasFacade: applied.includes('Generated by Update Guard') })
rollback(record)
const restored = readFileSync(join(work, 'live', 'index.js'), 'utf8')
console.log({ restoredOldMarker: restored.includes("old.slot") })
if (!meta.facade || !applied.includes('Generated by Update Guard') || !restored.includes('old.slot')) throw new Error('apply/rollback failed')
rmSync(work, { recursive: true, force: true })
